  /* ---------- intro ---------- */
  var intro=$('#intro'), fill=$('#introFill'), pct=$('#introPct'), skip=$('#introSkip');
  var done=false;
  function finishIntro(){
    if(done) return; done=true;
    document.body.classList.add('loaded');
    if(intro){ intro.classList.add('is-out'); setTimeout(function(){ intro.style.display='none'; },700); }
  }
  function runIntro(){
    if(STATIC){ if(intro) intro.style.display='none'; finishIntro(); return; }
    var start=performance.now(), D=2200;
    function tick(now){
      var p=Math.min(1,(now-start)/D);
      var e=p<.5?2*p*p:1-Math.pow(-2*p+2,2)/2;
      if(fill) fill.style.width=(e*100)+'%';
      if(pct) pct.textContent=Math.round(e*100)+'%';
      if(p<1){ requestAnimationFrame(tick); } else { finishIntro(); }
    }
    requestAnimationFrame(tick);
    setTimeout(finishIntro, D+700);
    var skipOnce=function(){ finishIntro(); };
    intro && intro.addEventListener('click',skipOnce,{once:true});
    document.addEventListener('keydown',function(e){ if(e.key==='Escape'||e.key==='Enter'||e.key===' ') finishIntro(); },{once:true});
  }
  if(skip) skip.addEventListener('click',function(e){ e.stopPropagation(); finishIntro(); });
  runIntro();

