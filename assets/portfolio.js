  /* ---------- ripple ---------- */
  function bindRipple(root){
    if(!root) return;
    $$('.btn,.logo,.topnav button,.section-card,.value,.project-tabs button,.project-switch button,.back,.full-link,.picker-item',root).forEach(function(b){
      if(b.__rip) return; b.__rip=true;
      b.addEventListener('click',function(e){
        var r=b.getBoundingClientRect();
        var s=document.createElement('span'); s.className='ripple';
        s.style.left=(e.clientX-r.left)+'px'; s.style.top=(e.clientY-r.top)+'px';
        b.appendChild(s); setTimeout(function(){ if(s.parentNode) s.parentNode.removeChild(s); },560);
      });
    });
  }
